// =======================
// LOAD COMPANIES
// =======================
function loadCompanies() {
    const company = document.getElementById("company");

    company.innerHTML = `
        <option value="">Select Company</option>
        <option value="NIL">NIL</option>
    `;

    Object.keys(companyProducts).forEach(c => {
        company.innerHTML += `<option value="${c}">${c}</option>`;
    });
}

// =======================
// COMPANY CHANGE
// =======================
function handleCompanyChange() {
    const company = document.getElementById("company").value;

    if (company === "NIL") {
        applyNilMode();
    } else {
        // 🔑 Reset ONLY if coming from NIL
        if (isNilMode) {
            resetNilModeCompletely();
            isNilMode = false;
        }
        updateProducts();
    }
}


// =======================
// UPDATE PRODUCTS
// =======================
function updateProducts() {
    const company = document.getElementById("company").value;
    const product = document.getElementById("product");

    product.innerHTML = `<option value="">Select Product</option>`;

    if (companyProducts[company]) {
        companyProducts[company].forEach(p => {
            product.innerHTML += `<option value="${p}">${p}</option>`;
        });
    }
}

// =======================
// AUTO SET PACK SIZE FROM PRODUCT NAME
// =======================
function autoSetPackSize() {
    const product = document.getElementById("product").value;
    const packSize = document.getElementById("packSize");

    if (!product || product === "NIL") {
        packSize.value = 0;
        return;
    }

    // Match 20 KG, 25 KGS, 40 KG, etc.
    const match = product.match(/(\d+)\s*KGS?|\s*KG/i);

    if (match && match[1]) {
        packSize.value = match[1];
    } else {
        packSize.value = ""; // fallback if not found
    }
packSize.disabled = true;
}

// =======================
// APPLY NIL MODE
// =======================
function applyNilMode() {
    isNilMode = true;

    // Product
    const product = document.getElementById("product");
    product.innerHTML = `<option value="NIL">NIL</option>`;
    product.value = "NIL";
    product.disabled = true;

    // Text fields
    const textFields = [
        "invoice","cinvoice",
        "driv","drivmn","truck",
        "partyName"
    ];

    textFields.forEach(id => {
        const el = document.getElementById(id);
        el.value = "NIL";
        el.readOnly = true;
        el.required = false;
    });

    // Number fields
    const numberFields = ["bags","qtyKg","qtyMT"];

    numberFields.forEach(id => {
        const el = document.getElementById(id);
        el.value = 0;
        el.readOnly = true;
        el.required = false;
    });

    // Pack size
    const packSize = document.getElementById("packSize");
    packSize.value = 0;
    packSize.disabled = true;
    packSize.required = false;

    // State code
    const stateCode = document.getElementById("stateCode");
    stateCode.innerHTML = `<option value="NIL">NIL</option>`;
    stateCode.value = "NIL";
    stateCode.disabled = true;
    stateCode.required = false;

    // Batch inputs
    const batchContainer = document.getElementById("batchContainer");
    batchContainer.innerHTML = "";
    const batchInput = document.createElement("input");
    batchInput.type = "text";
    batchInput.value = "NIL";
    batchInput.readOnly = true;
    batchInput.style.marginBottom = "10px";
    batchContainer.appendChild(batchInput);

    const batchCount = document.getElementById("batchCount");
    batchCount.value = 1;
    batchCount.disabled = true;

    // Time fields
    ["loadStart","unloadEnd"].forEach(id => {
        const el = document.getElementById(id);
        el.value = "00:00";
        el.readOnly = true;
        el.required = false;
    });

    // Work hours
    const workHours = document.getElementById("workHours");
    workHours.value = "0 hr 0 min";
    workHours.readOnly = true;
}

// =======================
// RESET NIL MODE
// =======================
function resetNilModeCompletely() {

    // Product
    const product = document.getElementById("product");
    product.disabled = false;
    product.innerHTML = `<option value="">Select Product</option>`;

    // Pack size
    const packSize = document.getElementById("packSize");
    packSize.disabled = false;
    packSize.required = true;
    packSize.value = "";

    // State
    const stateCode = document.getElementById("stateCode");
    stateCode.innerHTML = originalStateOptions;
    stateCode.disabled = false;
    stateCode.required = true;
    stateCode.value = "";

    // Restore text & number fields
    const fields = [
        "invoice","cinvoice",
        "driv","drivmn","truck",
        "partyName","bags"
    ];

    fields.forEach(id => {
        const el = document.getElementById(id);
        el.readOnly = false;
        el.required = true;
        el.value = "";
    });

    // Reset batch inputs
    document.getElementById("batchContainer").innerHTML = "";
    document.getElementById("batchCount").value = "";

    // Time fields
    ["loadStart","unloadEnd"].forEach(id => {
        const el = document.getElementById(id);
        el.readOnly = false;
        el.required = true;
        el.value = "";
    });

    document.getElementById("workHours").readOnly = false;
    document.getElementById("workHours").value = "";
    document.getElementById("qtyKg").value = "";
    document.getElementById("qtyMT").value = "";
}
